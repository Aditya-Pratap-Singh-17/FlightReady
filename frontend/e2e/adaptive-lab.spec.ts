import {test,expect} from '@playwright/test';

test('adaptive dimensions, task evidence, priority versions and real report exports',async({page})=>{
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  const models=await (await page.request.get('/api/v1/models')).json();
  expect(models.length,'Use the documented isolated smoke storage root').toBeGreaterThan(1);
  const candidate=models.find((m:any)=>m.payload.configuration.model_type==='candidate');
  await page.goto('/#Dataset%20Evaluation');
  await page.getByLabel('Working dataset').selectOption(candidate.payload.dataset_id);
  await page.getByLabel('Readiness report',{exact:true}).selectOption(candidate.payload.readiness_id);
  await expect(page.getByRole('heading',{name:'Multi-dimensional readiness profile'})).toBeVisible();
  await expect(page.locator('.wb-quality-card')).toHaveCount(6);
  await page.getByLabel('Aggregation task').selectOption('classification');
  await expect(page.getByText('Task preview needs new evidence.',{exact:true})).toBeVisible();
  await page.getByLabel('Aggregation task').selectOption('object_detection');
  await expect(page.getByText('Task preview needs new evidence.',{exact:true})).toHaveCount(0);
  const response=page.waitForResponse(r=>r.url().endsWith('/quality/aggregate')&&r.request().method()==='POST');
  await page.getByLabel('Scenario weighting policy').selectOption('nighttime_detection');
  const profile=await (await response).json();
  expect(profile.scenario).toBe('nighttime_detection');
  expect(profile.weight_explanations.join(' ')).toContain('engineering');
  await page.getByLabel('Signal and image quality priority multiplier',{exact:true}).fill('2');
  await page.getByRole('checkbox',{name:'I confirm these priority overrides'}).check();
  const save=page.waitForResponse(r=>r.url().endsWith('/quality/aggregate')&&r.request().postDataJSON().persist===true);
  await page.getByRole('button',{name:'Save aggregation version'}).click();
  const saved=await (await save).json();expect(saved.aggregation_id).toBeTruthy();
  await expect(page.getByRole('status').filter({hasText:'Aggregation version saved'})).toBeVisible();
  await page.getByRole('button',{name:'Compare contexts',exact:true}).click();
  await expect(page.getByText('Applicability, gate and weight differences',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Inspect Data integrity and reliability'}).click();
  await expect(page.getByRole('heading',{name:'Data integrity and reliability · metric evidence'})).toBeVisible();
  await page.getByRole('heading',{name:'Multi-dimensional readiness profile'}).scrollIntoViewIfNeeded();
  await page.screenshot({path:'../.runtime/browser-results/adaptive-quality-desktop.png'});
  for(const format of ['json','csv','html','pdf']){
    const report=await page.request.get(`/api/v1/reports/${candidate.payload.readiness_id}?format=${format}`);
    expect(report.status()).toBe(200);
    if(format==='pdf')expect((await report.body()).subarray(0,4).toString()).toBe('%PDF');
  }
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('heading',{name:'Multi-dimensional readiness profile'}).scrollIntoViewIfNeeded();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  await page.screenshot({path:'../.runtime/browser-results/adaptive-quality-mobile.png'});
  expect(errors).toEqual([]);
});

test('Model Validation Lab configures and executes a real reviewed candidate/reference protocol',async({page})=>{
  const models=await (await page.request.get('/api/v1/models')).json();
  const candidate=models.find((m:any)=>m.payload.configuration.model_type==='candidate');
  const reference=models.find((m:any)=>m.payload.configuration.model_type==='reference');
  const evaluations=await (await page.request.get('/api/v1/evaluations')).json();
  expect(candidate).toBeTruthy();expect(reference).toBeTruthy();
  await page.goto('/#Advanced%20Lab');
  await expect(page.getByRole('navigation',{name:'Model Validation Lab sections'}).getByRole('button')).toHaveCount(6);
  await page.getByRole('button',{name:'Experiment Builder',exact:true}).click();
  await page.getByLabel('Experiment name',{exact:true}).fill('Browser verification protocol');
  await page.getByLabel('Candidate dataset version').selectOption(candidate.payload.dataset_id);
  await page.getByLabel('Candidate train / validation split').selectOption(candidate.payload.configuration.split_id);
  await page.getByLabel('Candidate training readiness').selectOption(candidate.payload.readiness_id);
  await page.getByLabel('Reference dataset version').selectOption(reference.payload.dataset_id);
  await page.getByLabel('Reference train / validation split').selectOption(reference.payload.configuration.split_id);
  await page.getByLabel('Reference training readiness').selectOption(reference.payload.readiness_id);
  await page.getByLabel('Shared validation dataset').selectOption(reference.payload.dataset_id);
  await page.getByLabel('Shared validation partition').selectOption(reference.payload.configuration.split_id);
  await page.getByLabel('Lab independent test dataset').selectOption(evaluations[0].payload.dataset_id);
  await page.getByLabel('Lab Epoch budget').fill('1');await page.getByLabel('Lab Batch').fill('2');await page.getByLabel('Lab Image size').fill('64');
  await page.getByText('Device',{exact:true}).locator('..').getByRole('combobox').selectOption('cpu');
  const createdResponse=page.waitForResponse(r=>r.url().endsWith('/api/v1/experiments')&&r.request().method()==='POST');
  await page.getByRole('button',{name:'Create and review protocol'}).click();
  const created=await (await createdResponse).json();expect(created.id).toBeTruthy();
  await expect(page.getByRole('button',{name:'Start reviewed experiment'})).toBeVisible();
  const startedResponse=page.waitForResponse(r=>r.url().endsWith(`/experiments/${created.id}/start`));
  await page.getByRole('button',{name:'Start reviewed experiment'}).click();
  const started=await (await startedResponse).json();
  await expect.poll(async()=>(await (await page.request.get('/api/v1/jobs/'+started.id)).json()).payload.status,{timeout:100000}).toBe('completed');
  const experiment=await (await page.request.get('/api/v1/experiments/'+created.id)).json();
  expect(experiment.payload.model_ids).toHaveLength(2);expect(experiment.payload.evaluation_ids).toHaveLength(2);
  await page.getByRole('button',{name:'Model Benchmarking',exact:true}).click();
  await page.getByLabel('Model A evaluation').selectOption(experiment.payload.evaluation_ids[0]);
  await page.getByLabel('Model B evaluation').selectOption(experiment.payload.evaluation_ids[1]);
  await expect(page.getByText('Ground truth',{exact:true})).toBeVisible();
  await expect(page.getByRole('heading',{name:'Detection confusion matrix'})).toHaveCount(2);
  await page.screenshot({path:'../.runtime/browser-results/lab-benchmark-desktop.png'});
  const report=await page.request.get(`/api/v1/reports/${created.id}?format=pdf`);expect(report.status()).toBe(200);
  await page.getByRole('button',{name:'Quality–Performance Analysis',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Predictive validity and held-out dataset analysis'})).toBeVisible();
});
