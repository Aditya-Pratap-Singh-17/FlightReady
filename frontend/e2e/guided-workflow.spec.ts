import {test,expect} from '@playwright/test';
import {mkdir} from 'node:fs/promises';
import path from 'node:path';

test('guided upload, saved goal, real readiness and paired training comparison',async({page})=>{
  test.setTimeout(300000);
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  const screenshots=path.resolve('../.runtime/guided-ui-verification/screenshots');await mkdir(screenshots,{recursive:true});
  await page.goto('/');
  await expect(page.getByRole('heading',{name:'Good decisions start with your data.'})).toBeVisible();
  await expect(page.getByRole('navigation',{name:'Main navigation'}).getByRole('button')).toHaveCount(3);
  await expect(page.getByRole('navigation',{name:'Project workflow'}).getByRole('button').nth(1)).toBeDisabled();
  await expect(page.getByRole('button',{name:'Analyze dataset',exact:true})).toHaveCount(0);
  await page.screenshot({path:path.join(screenshots,'01-start-desktop.png')});
  await page.setViewportSize({width:390,height:844});
  await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  await page.screenshot({path:path.join(screenshots,'01-start-mobile.png'),fullPage:true});
  await page.setViewportSize({width:1440,height:1000});
  await page.getByLabel('Upload dataset',{exact:true}).setInputFiles(process.env.GUIDED_FIXTURE||'../.runtime/guided-ui-verification/synthetic-drones.zip');
  await expect(page.getByRole('heading',{name:'What do you want to achieve?'})).toBeVisible();
  await page.getByLabel('Describe your goal').fill('Detect drones in images.');
  const interpreted=page.waitForResponse(r=>r.url().endsWith('/goal')&&r.request().method()==='POST');
  await page.getByRole('button',{name:'Interpret goal',exact:true}).click();
  const interpretedData=await (await interpreted).json();const workflowId=interpretedData.id;
  expect(interpretedData.payload.context.provider).toBe('deterministic');
  await expect(page.getByRole('heading',{name:'Review the goal before analysis'})).toBeVisible();
  await expect(page.getByLabel('Goal task')).toHaveValue('object_detection');
  await expect(page.getByLabel('Goal prediction target')).toHaveValue('drone');
  await page.screenshot({path:path.join(screenshots,'02-goal-review.png'),fullPage:true});
  await page.getByRole('button',{name:'Confirm & save goal'}).click();
  await expect(page.getByRole('heading',{name:'Goal confirmed'})).toBeVisible();
  await page.reload();
  await expect(page.getByRole('heading',{name:'Goal confirmed'})).toBeVisible();
  await page.getByRole('button',{name:'Continue to analysis'}).click();
  await expect(page.getByRole('heading',{name:'Turn your goal into measurable answers.'})).toBeVisible();
  await page.getByRole('button',{name:'Analyze dataset',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Your data, through the lens of your goal.'})).toBeVisible({timeout:60000});
  await expect(page.locator('.flow-dimension-overview>div')).toHaveCount(6);
  await expect(page.getByRole('heading',{name:'What needs attention first?'})).toBeVisible();
  await page.screenshot({path:path.join(screenshots,'03-readiness-report.png'),fullPage:true});
  await page.getByRole('button',{name:'Quality & visual evidence'}).click();
  await expect(page.getByRole('heading',{name:'Multi-dimensional readiness profile'})).toBeVisible();
  await page.getByRole('button',{name:'Open Model Validation Lab',exact:true}).click();
  await page.getByRole('button',{name:'Controlled training comparison',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Which data quality change should we investigate?'})).toBeVisible();
  await expect(page.getByRole('button',{name:'Start training & comparison'})).toHaveCount(0);
  await page.getByRole('button',{name:'Prepare comparison',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Set the training budget.'})).toBeVisible({timeout:60000});
  await page.getByLabel('Validation training epochs').fill('1');
  await page.getByLabel('Validation batch size').fill('2');
  await page.getByLabel('Validation image size').selectOption('64');
  await page.getByRole('button',{name:'Review experiment',exact:true}).click();
  await expect(page.getByRole('heading',{name:'One shared protocol. Two training datasets.'})).toBeVisible();
  await page.screenshot({path:path.join(screenshots,'04-experiment-review.png'),fullPage:true});
  await page.getByRole('button',{name:'Start training & comparison'}).click();
  await expect(page.getByRole('heading',{name:'Your controlled comparison is complete.'})).toBeVisible({timeout:180000});
  await expect(page.getByRole('heading',{name:'Original data vs. controlled data'})).toBeVisible();
  await page.screenshot({path:path.join(screenshots,'05-comparison-outcomes.png'),fullPage:true});
  await page.getByRole('button',{name:'Benchmark visualizations',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Detection confusion matrix'})).toHaveCount(2);
  await page.setViewportSize({width:390,height:844});
  await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  await page.screenshot({path:path.join(screenshots,'06-model-benchmarks-mobile.png'),fullPage:true});
  await page.getByRole('button',{name:'Toggle color theme'}).click();
  await page.screenshot({path:path.join(screenshots,'07-model-benchmarks-dark.png')});
  const workflow=await (await page.request.get('/api/v1/workflows/'+workflowId)).json();
  const context=workflow.payload.context;
  expect(context.confirmed).toBe(true);expect(workflow.payload.confirmed_context_id).toBeTruthy();
  const assessment=await (await page.request.get('/api/v1/jobs/'+workflow.payload.readiness_id)).json();
  expect(assessment.payload.config.context).toEqual(context);
  const validation=await (await page.request.get('/api/v1/workflow-validations/'+workflow.payload.validation_id)).json();
  const experiment=await (await page.request.get('/api/v1/experiments/'+validation.payload.experiment_id)).json();
  expect(experiment.payload.model_ids).toHaveLength(2);expect(experiment.payload.evaluation_ids).toHaveLength(2);
  expect(errors).toEqual([]);
});
